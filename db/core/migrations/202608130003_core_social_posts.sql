-- Social posts are a small, independently versioned aggregate. The first
-- release intentionally stores public plain text only; media, follows, likes,
-- tips and ranking must arrive as separate reviewed capabilities instead of
-- being implied by nullable columns that no use case owns.
CREATE TABLE social.posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    public_id uuid NOT NULL UNIQUE,
    author_id uuid NOT NULL
        REFERENCES identity.users (id) ON DELETE RESTRICT,
    create_request_id uuid NOT NULL,
    create_body_sha256 bytea NOT NULL
        CHECK (octet_length(create_body_sha256) = 32),
    body text NOT NULL,
    body_format text NOT NULL DEFAULT 'plain_text'
        CHECK (body_format = 'plain_text'),
    state text NOT NULL DEFAULT 'visible'
        CHECK (state IN ('visible', 'author_deleted')),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    edited_at timestamptz,
    deleted_at timestamptz,
    UNIQUE (author_id, create_request_id),
    CHECK (char_length(body) <= 2000),
    CHECK (
        (state = 'visible' AND char_length(btrim(body)) BETWEEN 1 AND 2000 AND deleted_at IS NULL)
        OR
        (state = 'author_deleted' AND body = '' AND deleted_at IS NOT NULL)
    ),
    CHECK (updated_at >= created_at),
    CHECK (edited_at IS NULL OR (edited_at >= created_at AND edited_at <= updated_at)),
    CHECK (deleted_at IS NULL OR (deleted_at >= created_at AND deleted_at <= updated_at))
);

CREATE INDEX social_posts_visible_feed_idx
    ON social.posts (created_at DESC, id DESC)
    WHERE state = 'visible';

CREATE INDEX social_posts_author_recent_idx
    ON social.posts (author_id, created_at DESC, id DESC);

-- Revisions retain the previous visible body for governance and lost-response
-- diagnosis. They are internal evidence and never cross the public API.
CREATE TABLE social.post_revisions (
    post_id bigint NOT NULL
        REFERENCES social.posts (id) ON DELETE RESTRICT,
    version bigint NOT NULL CHECK (version > 0),
    body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 2000),
    reason text NOT NULL CHECK (reason IN ('author_edit', 'author_delete')),
    editor_id uuid NOT NULL
        REFERENCES identity.users (id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (post_id, version)
);

-- +goose StatementBegin
CREATE FUNCTION social.protect_post_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'social posts must be tombstoned, not deleted';
    END IF;
    IF OLD.id IS DISTINCT FROM NEW.id
        OR OLD.public_id IS DISTINCT FROM NEW.public_id
        OR OLD.author_id IS DISTINCT FROM NEW.author_id
        OR OLD.create_request_id IS DISTINCT FROM NEW.create_request_id
        OR OLD.create_body_sha256 IS DISTINCT FROM NEW.create_body_sha256
        OR OLD.body_format IS DISTINCT FROM NEW.body_format
        OR OLD.created_at IS DISTINCT FROM NEW.created_at THEN
        RAISE EXCEPTION 'social post identity is immutable';
    END IF;
    IF OLD.state <> 'visible'
        OR NEW.version <> OLD.version + 1
        OR NEW.updated_at < OLD.updated_at THEN
        RAISE EXCEPTION 'social post transition is invalid';
    END IF;
    IF NEW.state = 'visible' THEN
        IF NEW.body IS NOT DISTINCT FROM OLD.body
            OR NEW.edited_at IS DISTINCT FROM NEW.updated_at
            OR NEW.deleted_at IS NOT NULL THEN
            RAISE EXCEPTION 'visible social post update must be a body edit';
        END IF;
    ELSIF NEW.state = 'author_deleted' THEN
        IF NEW.body <> ''
            OR NEW.deleted_at IS DISTINCT FROM NEW.updated_at
            OR NEW.edited_at IS DISTINCT FROM OLD.edited_at THEN
            RAISE EXCEPTION 'social post deletion must create a terminal tombstone';
        END IF;
    ELSE
        RAISE EXCEPTION 'invalid social post state transition';
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER social_post_history_protected
BEFORE UPDATE OR DELETE ON social.posts
FOR EACH ROW EXECUTE FUNCTION social.protect_post_history();

-- +goose StatementBegin
CREATE FUNCTION social.reject_post_revision_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'social post revisions are immutable';
END;
$$;
