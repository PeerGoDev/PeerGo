-- Posts use the same typed-binding comment architecture as torrents and
-- announcements. The shared projection is polymorphic; persisted ownership is
-- still enforced by this real foreign key.
CREATE TABLE social.post_comment_threads (
    thread_id bigint PRIMARY KEY,
    target_kind text NOT NULL DEFAULT 'post' CHECK (target_kind = 'post'),
    post_id bigint NOT NULL UNIQUE
        REFERENCES social.posts (id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL,
    FOREIGN KEY (thread_id, target_kind)
        REFERENCES social.comment_threads (id, target_kind) ON DELETE RESTRICT
);

DROP VIEW social.comment_target_projection;

CREATE VIEW social.comment_target_projection AS
SELECT
    binding.thread_id,
    'torrent'::text AS target_kind,
    torrent.public_id::text AS target_key,
    torrent.title AS target_title,
    (torrent.state = 'published') AS target_is_public
FROM torrents.torrents AS torrent
LEFT JOIN social.torrent_comment_threads AS binding
    ON binding.torrent_id = torrent.id
UNION ALL
SELECT
    binding.thread_id,
    'announcement'::text AS target_kind,
    announcement.id AS target_key,
    COALESCE(
        CASE
            WHEN announcement.scheduled_for <= CURRENT_TIMESTAMP
                THEN scheduled_revision.title
            ELSE published_revision.title
        END,
        scheduled_revision.title,
        published_revision.title,
        draft_revision.title
    ) AS target_title,
    (
        announcement.withdrawn_at IS NULL
        AND CASE
            WHEN announcement.scheduled_for <= CURRENT_TIMESTAMP
                THEN announcement.scheduled_revision_id IS NOT NULL
            ELSE announcement.published_revision_id IS NOT NULL
        END
    ) AS target_is_public
FROM catalog.announcements AS announcement
LEFT JOIN catalog.announcement_revisions AS published_revision
    ON published_revision.id = announcement.published_revision_id
LEFT JOIN catalog.announcement_revisions AS scheduled_revision
    ON scheduled_revision.id = announcement.scheduled_revision_id
LEFT JOIN catalog.announcement_revisions AS draft_revision
    ON draft_revision.id = announcement.draft_revision_id
LEFT JOIN social.announcement_comment_threads AS binding
    ON binding.announcement_id = announcement.id
UNION ALL
SELECT
    binding.thread_id,
    'post'::text AS target_kind,
    post.public_id::text AS target_key,
    left(post.body, 160) AS target_title,
    (post.state = 'visible') AS target_is_public
FROM social.posts AS post
LEFT JOIN social.post_comment_threads AS binding
    ON binding.post_id = post.id;

-- Moderation evidence mirrors the typed target binding. Existing torrent and
-- announcement decisions are backfilled unchanged; new post decisions must
-- carry exactly one post UUID.
ALTER TABLE social.comment_moderation_decisions
    DROP CONSTRAINT comment_moderation_decisions_target_identity_check,
    DROP CONSTRAINT comment_moderation_decisions_target_kind_check,
    ADD COLUMN post_public_id uuid,
    ADD CONSTRAINT comment_moderation_decisions_target_kind_check
        CHECK (target_kind IN ('torrent', 'announcement', 'post')),
    ADD CONSTRAINT comment_moderation_decisions_target_identity_check
        CHECK (
            (target_kind = 'torrent'
                AND torrent_public_id IS NOT NULL
                AND announcement_id IS NULL
                AND post_public_id IS NULL)
            OR
            (target_kind = 'announcement'
                AND torrent_public_id IS NULL
                AND announcement_id IS NOT NULL
                AND post_public_id IS NULL)
            OR
            (target_kind = 'post'
                AND torrent_public_id IS NULL
                AND announcement_id IS NULL
                AND post_public_id IS NOT NULL)
        ),
    ADD CONSTRAINT comment_moderation_decisions_post_fk
        FOREIGN KEY (post_public_id)
        REFERENCES social.posts (public_id) ON DELETE RESTRICT;

