-- Post reports follow the comment moderation model: one open case aggregates
-- every report against the same post, while reports and decisions remain
-- immutable evidence. A terminal case is never reopened; a later report
-- against a still-visible post opens a new case.
CREATE TABLE social.post_moderation_cases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    public_id uuid NOT NULL UNIQUE,
    post_id bigint NOT NULL
        REFERENCES social.posts (id) ON DELETE RESTRICT,
    state text NOT NULL DEFAULT 'open'
        CHECK (state IN ('open', 'dismissed', 'post_hidden')),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    opened_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    resolved_at timestamptz,
    CHECK (updated_at >= opened_at),
    CHECK (resolved_at IS NULL OR (resolved_at >= opened_at AND resolved_at <= updated_at)),
    CHECK (
        (state = 'open' AND resolved_at IS NULL)
        OR
        (state <> 'open' AND resolved_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX post_moderation_cases_one_open_per_post_idx
    ON social.post_moderation_cases (post_id)
    WHERE state = 'open';

CREATE INDEX post_moderation_cases_open_queue_idx
    ON social.post_moderation_cases (opened_at, id)
    WHERE state = 'open';

-- Reporter identity stays in Core for duplicate and conflict-of-interest
-- checks, but is intentionally absent from staff DTOs.
CREATE TABLE social.post_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    public_id uuid NOT NULL UNIQUE,
    case_id bigint NOT NULL
        REFERENCES social.post_moderation_cases (id) ON DELETE RESTRICT,
    reporter_id uuid NOT NULL
        REFERENCES identity.users (id) ON DELETE RESTRICT,
    create_request_id uuid NOT NULL,
    create_input_sha256 bytea NOT NULL
        CHECK (octet_length(create_input_sha256) = 32),
    reason_code text NOT NULL
        CHECK (reason_code IN ('spam', 'harassment', 'personal_information', 'off_topic', 'other')),
    details text NOT NULL DEFAULT '' CHECK (char_length(details) <= 500),
    created_at timestamptz NOT NULL,
    UNIQUE (reporter_id, create_request_id),
    UNIQUE (case_id, reporter_id)
);

CREATE INDEX post_reports_case_chronological_idx
    ON social.post_reports (case_id, created_at, id);

-- A case has at most one immutable decision. Hiding a post reuses the staff
-- post moderation transition and its post_management_events evidence, so the
-- note is bounded by that table's reason length.
CREATE TABLE social.post_moderation_decisions (
    id uuid PRIMARY KEY,
    case_id bigint NOT NULL UNIQUE
        REFERENCES social.post_moderation_cases (id) ON DELETE RESTRICT,
    case_public_id uuid NOT NULL,
    post_public_id uuid NOT NULL
        REFERENCES social.posts (public_id) ON DELETE RESTRICT,
    moderator_id uuid NOT NULL
        REFERENCES identity.users (id) ON DELETE RESTRICT,
    decision text NOT NULL CHECK (decision IN ('dismiss', 'hide_post')),
    reason_code text NOT NULL
        CHECK (reason_code IN ('no_violation', 'spam', 'harassment', 'personal_information', 'off_topic', 'other')),
    note text NOT NULL CHECK (char_length(btrim(note)) BETWEEN 10 AND 500),
    expected_case_version bigint NOT NULL CHECK (expected_case_version > 0),
    resulting_case_version bigint NOT NULL CHECK (resulting_case_version = expected_case_version + 1),
    expected_post_version bigint NOT NULL CHECK (expected_post_version > 0),
    resulting_post_version bigint NOT NULL CHECK (resulting_post_version >= expected_post_version),
    resulting_case_state text NOT NULL
        CHECK (resulting_case_state IN ('dismissed', 'post_hidden')),
    resulting_post_state text NOT NULL
        CHECK (resulting_post_state IN ('visible', 'author_deleted', 'moderator_hidden')),
    authorization_decision_id uuid NOT NULL,
    decided_at timestamptz NOT NULL,
    CHECK (
        (decision = 'dismiss' AND reason_code = 'no_violation'
            AND resulting_case_state = 'dismissed'
            AND resulting_post_version = expected_post_version)
        OR
        (decision = 'hide_post' AND reason_code <> 'no_violation'
            AND resulting_case_state = 'post_hidden'
            AND resulting_post_state = 'moderator_hidden'
            AND resulting_post_version = expected_post_version + 1)
    )
);

-- +goose StatementBegin
CREATE FUNCTION social.protect_post_moderation_case()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'post moderation cases cannot be deleted';
    END IF;
    IF OLD.id IS DISTINCT FROM NEW.id
        OR OLD.public_id IS DISTINCT FROM NEW.public_id
        OR OLD.post_id IS DISTINCT FROM NEW.post_id
        OR OLD.opened_at IS DISTINCT FROM NEW.opened_at THEN
        RAISE EXCEPTION 'post moderation case identity is immutable';
    END IF;
    IF OLD.state <> 'open'
        OR NEW.state NOT IN ('dismissed', 'post_hidden')
        OR NEW.version <> OLD.version + 1
        OR NEW.updated_at < OLD.updated_at
        OR NEW.resolved_at IS DISTINCT FROM NEW.updated_at THEN
        RAISE EXCEPTION 'post moderation case transition is invalid';
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER post_moderation_case_protected
BEFORE UPDATE OR DELETE ON social.post_moderation_cases
FOR EACH ROW EXECUTE FUNCTION social.protect_post_moderation_case();

-- +goose StatementBegin
CREATE FUNCTION social.reject_post_moderation_evidence_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'post moderation evidence is immutable';
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER post_reports_immutable
BEFORE UPDATE OR DELETE ON social.post_reports
FOR EACH ROW EXECUTE FUNCTION social.reject_post_moderation_evidence_mutation();

CREATE TRIGGER post_moderation_decisions_immutable
BEFORE UPDATE OR DELETE ON social.post_moderation_decisions
FOR EACH ROW EXECUTE FUNCTION social.reject_post_moderation_evidence_mutation();

